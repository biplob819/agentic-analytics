"""The bundled SYNTHETIC example run, so `agentic-analytics report --example` needs no keys.

The files under `report/example/` are generated by `tests/report/example_data.py` from fixed
synthetic rates (not measurements) and summarised by `aggregate.build_summary`; a test keeps
them byte-identical to what the generator produces.
"""

from __future__ import annotations

import os
from importlib import resources
from importlib.resources.abc import Traversable
from pathlib import Path

from agentic_analytics.report.render import render_report
from agentic_analytics.schemas import Question, Record, RunSummary

EXAMPLE_RUN_ID = "example-synthetic"


def example_root() -> Traversable:
    return resources.files("agentic_analytics.report").joinpath("example")


def _jsonl(t: Traversable) -> list[str]:
    return [ln for ln in t.read_text(encoding="utf-8").splitlines() if ln.strip()]


def load_example() -> tuple[RunSummary, list[Record], dict[str, Question]]:
    """(summary, the bundled failure records, the questions they refer to)."""
    root = example_root()
    summary = RunSummary.model_validate_json(root.joinpath("summary.json").read_text("utf-8"))
    records = [Record.model_validate_json(ln) for ln in _jsonl(root.joinpath("records.jsonl"))]
    questions = [
        Question.model_validate_json(ln) for ln in _jsonl(root.joinpath("questions.jsonl"))
    ]
    return summary, records, {q.id: q for q in questions}


def render_example(out_dir: str | os.PathLike[str]) -> Path:
    """Render the example dashboard into `out_dir`, with its exported traces under `traces/`."""
    summary, records, questions = load_example()
    path = render_report(summary, records, out_dir, questions=questions, example=True)
    traces = Path(out_dir) / "traces"
    traces.mkdir(exist_ok=True)
    src = example_root().joinpath("traces")
    for t in sorted(src.iterdir(), key=lambda t: t.name):
        if t.name.endswith(".json"):
            (traces / t.name).write_bytes(t.read_bytes())
    return path
