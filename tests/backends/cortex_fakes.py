class Clock:
    """A settable wall clock for the JWT cache."""

    def __init__(self, now: float = 1_800_000_000.0) -> None:
        self.now = now

    def __call__(self) -> float:
        return self.now


def ticks(*values: float) -> Callable[[], float]:
    """A perf clock that returns the given values in order, then repeats the last."""
    it = iter(values)
    last = [values[-1]]

    def clock() -> float:
        last[0] = next(it, last[0])
        return last[0]

    return clock


def text_block(text: str = "This is our interpretation of your question: ...") -> dict[str, Any]:
    return {"type": "text", "text": text}


def sql_block(statement: str = SQL, verified: dict[str, Any] | None = None) -> dict[str, Any]:
    return {"type": "sql", "statement": statement, "confidence": {"verified_query_used": verified}}


def suggestions_block(*items: str, kind: str = "suggestions", key: str = "suggestions") -> dict:
    return {"type": kind, key: list(items)}


def body(
    *content: Any,
    request_id: str | None = "req-0001",
    warnings: Sequence[str] = (),
    model_names: Sequence[str] = MODELS,
    category: str | None = "UNAMBIGUOUS_SQL",
) -> dict[str, Any]:
    out: dict[str, Any] = {
        "message": {"role": "analyst", "content": list(content)},
        "warnings": [{"message": w} for w in warnings],
        "response_metadata": {"model_names": list(model_names), "question_category": category},
    }
    if request_id is not None:
        out["request_id"] = request_id
    return out


def sql_body(**kw: Any) -> dict[str, Any]:
    return body(text_block(), sql_block(), **kw)


@dataclass(frozen=True)
class Hang:
    """A reply that takes `seconds` of real time (for the deadline tests)."""

    seconds: float


class FailingStream(httpx2.AsyncByteStream):
    """A response body that fails while being read, after the status line arrived."""

    def __init__(self, exc: Exception, first: bytes = b"") -> None:
        self.exc = exc
        self.first = first

    async def __aiter__(self):
        if self.first:
            yield self.first
        raise self.exc


def garbled(status: int = 200) -> httpx2.Response:
    """A reply whose body claims gzip but is not: reading it raises `httpx2.DecodingError`."""
    return httpx2.Response(
        status, stream=httpx2.ByteStream(b"not gzip"), headers={"Content-Encoding": "gzip"}
    )


def broken_body(exc: Exception, status: int = 200) -> httpx2.Response:
    return httpx2.Response(status, stream=FailingStream(exc, b'{"message"'))


Step = httpx2.Response | Exception | dict[str, Any] | bytes | Hang


@dataclass
class Api:
    """A scripted Cortex endpoint. Each request consumes the next step."""

    script: list[Step]
    requests: list[httpx2.Request] = field(default_factory=list)

    async def handler(self, request: httpx2.Request) -> httpx2.Response:
        self.requests.append(request)
        if not self.script:
            raise AssertionError("the fake API ran out of scripted replies")
        step = self.script.pop(0)
        if isinstance(step, Hang):
            await asyncio.sleep(step.seconds)
            return httpx2.Response(200, json=body(text_block()))
        if isinstance(step, Exception):
            raise step
        if isinstance(step, httpx2.Response):
            return step
        if isinstance(step, bytes):
            return httpx2.Response(200, content=step)
        return httpx2.Response(200, json=step)

    @property
    def transport(self) -> httpx2.MockTransport:
        return httpx2.MockTransport(self.handler)

    def bodies(self) -> list[Any]:
        return [json.loads(r.content) for r in self.requests]


def error(status: int, message: str = "boom", code: str = "390000") -> httpx2.Response:
    return httpx2.Response(
        status, json={"code": code, "message": message, "request_id": f"err-{status}"}
    )


def execution(
    rows: Iterable[Sequence[Any]] = ((254_312.5,),),
    columns: Sequence[str] = ("MEDIAN_PRICE",),
    *,
    sql: str = SQL,
    rows_total: int | None = None,
    error: str | None = None,
    elapsed_ms: int = 420,
    engine: str = "snowflake",
) -> Execution:
    if error is not None:
        return Execution.model_validate(
            dict(
                engine=engine,
                sql=sql,
                result=None,
                rows_total=None,
                truncated=False,
                query_id="01b0-err",
                elapsed_ms=elapsed_ms,
                error=error,
            )
        )
    kept = tuple(tuple(r) for r in rows)
    total = len(kept) if rows_total is None else rows_total
    return Execution.model_validate(
        dict(
            engine=engine,
            sql=sql,
            result=ResultSet(columns=tuple(columns), rows=kept),
            rows_total=total,
            truncated=total > len(kept),
            query_id="01b0-ok",
            elapsed_ms=elapsed_ms,
        )
    )


@dataclass
class FakeExecutor:
    """Satisfies the `SqlExecutor` protocol; returns a scripted Execution (or raises)."""

    result: Execution | Exception = field(default_factory=execution)
    calls: list[tuple[str, int]] = field(default_factory=list)

    def execute(self, sql: str, *, row_cap: int) -> Execution:
        self.calls.append((sql, row_cap))
        if isinstance(self.result, Exception):
            raise self.result
        return self.result


async def no_sleep(_: float) -> None:
    return None


def make_jwt(clock: Clock | None = None, **kw: Any) -> KeyPairJwt:
    return KeyPairJwt(ACCOUNT, USER, rsa_key(), clock=clock or Clock(), **kw)


def make_client(api: Api, *, jwt_source: KeyPairJwt | None = None, **kw: Any) -> CortexClient:
    kw.setdefault("sleep", no_sleep)
    return CortexClient(ACCOUNT, VIEW, jwt_source or make_jwt(), transport=api.transport, **kw)


def run(
    *script: Step,
    executor: FakeExecutor | None = None,
    question: str = "What was the median price in Manchester in 2024?",
    **kw: Any,
) -> tuple[CortexRun, Api, FakeExecutor]:
    api = Api(list(script))
    ex = executor or FakeExecutor()
    client_kw = {
        k: kw.pop(k)
        for k in ("jwt_source", "sleep", "timeout_s", "deadline_s", "base_url")
        if k in kw
    }
    client = make_client(api, **client_kw)
    out = asyncio.run(ask_cortex(question, client, ex, **kw))
    return out, api, ex
