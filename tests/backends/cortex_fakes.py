"""Fakes for the Cortex Analyst backend tests (A2.2), built from real objects (EK L-17).

- RSA keys are real `cryptography` keys; tokens are checked with real PyJWT verification.
- The API is a real `httpx2.MockTransport` that replays a script of responses or exceptions and
  records every request it saw.
- Built bodies follow the documented response shape (Snowflake docs, checked 2026-11-15);
  `recorded(name)` returns a real reply recorded from the live API on 2026-11-16
  (`fixtures/cortex/`, request ids redacted), and `test_cortex_recorded.py` runs the parser,
  the guard and `ask_cortex` over those.
- The executor returns real `Execution` objects, so every invariant of the schema applies.
"""

