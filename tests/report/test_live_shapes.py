def _items(page: str) -> dict[str, str]:
    found = re.findall(
        r'(<details data-backend="([a-z_]+)"[^>]*><summary>(q-\d+)[^<]*</summary>.*?</details>)',
        section(page, "failures"),
        re.S,
    )
    return {f"{qid}:{backend}": item for item, backend, qid in found}


