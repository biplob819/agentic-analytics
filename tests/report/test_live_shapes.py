def _live(r: Record, *, sql: str, rows, columns, answer: str, question: str, **kw) -> Record:
    """`r` re-pointed at a recorded live answer, assembled by A2.3 as the runner does."""
    ex = f.execution(
        engine=r.execution.engine,  # type: ignore[union-attr]
        sql=sql,
        result=ResultSet(columns=columns, rows=rows),
        rows_total=len(rows),
        elapsed_ms=kw.pop("elapsed_ms", 900),
    )
    a = r.answer.model_copy(update={"sql": sql, "answer": answer, **kw})
    trace = f"results/{RUN}/traces/{r.question_id}-{r.backend}-{r.trial}.json"
    a = assemble(a, ex, question_text=question).model_copy(update={"trace_export": trace})
    return r.model_copy(update={"run_id": RUN, "answer": a, "execution": ex})


